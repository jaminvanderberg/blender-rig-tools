ARM_PREFIXES = ('DEF-arm', 'DEF-forearm', 'DEF-hand', 'DEF-palm', 'DEF-finger', 'DEF-thumb')
FINGER_TOKENS = ('-palm', '-finger', '-thumb')


def _mirror_name(name):
	if name is None:
		return None
	if name.endswith('.L'):
		return name[:-2] + '.R'
	return name


def _mirror_entry(entry):
	name, parent, head, tail, roll, use_deform, use_connect, collection = entry
	return (
		_mirror_name(name),
		_mirror_name(parent),
		(-head[0], head[1], head[2]),
		(-tail[0], tail[1], tail[2]),
		-roll,
		use_deform,
		use_connect,
		collection,
	)


def _is_finger(name):
	return any(token in name for token in FINGER_TOKENS)


def _bone_entries(include_fingers):
	entries = list(CENTER_BONES)
	for entry in LEFT_BONES:
		entries.append(entry)
		entries.append(_mirror_entry(entry))
	if not include_fingers:
		entries = [entry for entry in entries if not _is_finger(entry[0])]
	return entries


class RIG_OT_create_human_skeleton(bpy.types.Operator):
	bl_idname = "rig.create_human_skeleton"
	bl_label = "RigTools Human Skeleton"
	bl_description = "Create a human DEF skeleton ready for fitting"
	bl_options = {'REGISTER', 'UNDO'}

	height: FloatProperty(
		name="Height",
		description="Total skeleton height",
		default=AUTHORED_HEIGHT,
		min=0.5,
		max=3.0,
		unit='LENGTH',
	)
	pose: EnumProperty(
		name="Pose",
		description="Arm pose for the new skeleton",
		items=[
			('A', "A-Pose", "Arms lowered 45 degrees"),
			('T', "T-Pose", "Arms horizontal"),
		],
		default='A',
	)
	include_fingers: BoolProperty(
		name="Include Fingers",
		description="Create palm, finger, and thumb bones",
		default=True,
	)
	apply_root_widgets: BoolProperty(
		name="Apply Root Widgets",
		description="Apply widgets to the root and properties bones",
		default=True,
	)

	def execute(self, context):
		prefs = get_preferences(context)
		name_map = {
			'root': prefs.root_bone_name,
			'properties': prefs.property_bone_name,
		}
		scale = self.height / AUTHORED_HEIGHT

		armature_data = bpy.data.armatures.new("RigTools Human")
		obj = bpy.data.objects.new("RigTools Human", armature_data)
		context.scene.collection.objects.link(obj)
		obj.location = context.scene.cursor.location

		for selected in context.selected_objects:
			selected.select_set(False)
		obj.select_set(True)
		context.view_layer.objects.active = obj

		entries = _bone_entries(self.include_fingers)
		arm_pivots = {}
		if self.pose == 'A':
			for entry in entries:
				if entry[0].startswith('DEF-arm'):
					side = 1.0 if entry[0].endswith('.L') else -1.0
					arm_pivots[entry[0][-2:]] = (Vector(entry[2]) * scale, side)

		bpy.ops.object.mode_set(mode='EDIT')
		edit_bones = armature_data.edit_bones
		created = {}

		for name, parent, head, tail, roll, use_deform, use_connect, collection_name in entries:
			resolved_name = name_map.get(name, name)
			head_vec = Vector(head) * scale
			tail_vec = Vector(tail) * scale

			bone = edit_bones.new(resolved_name)
			bone.head = head_vec
			bone.tail = tail_vec
			bone.roll = roll
			bone.use_deform = use_deform

			if self.pose == 'A' and name.startswith(ARM_PREFIXES):
				pivot, side = arm_pivots[name[-2:]]
				rotation = Matrix.Rotation(math.radians(A_POSE_ANGLE) * side, 4, 'Y')
				z_axis = bone.matrix.to_3x3() @ Vector((0, 0, 1))
				bone.head = pivot + rotation @ (bone.head - pivot)
				bone.tail = pivot + rotation @ (bone.tail - pivot)
				bone.align_roll(rotation @ z_axis)

			add_bone_collection(armature_data, bone, collection_name)

			created[name] = bone

		for name, parent, head, tail, roll, use_deform, use_connect, collection_name in entries:
			if parent is None:
				continue
			bone = created[name]
			bone.parent = created[parent]
			bone.use_connect = use_connect

		set_heel_pivot(armature_data, 'DEF-foot.L', 'PIVOT-heel.L')
		set_heel_pivot(armature_data, 'DEF-foot.R', 'PIVOT-heel.R')

		select_bones(obj, [created['root'].name], select_hidden=True, deselect=True)

		bpy.ops.object.mode_set(mode='OBJECT')
		get_armature_settings(armature_data, context)

		if self.apply_root_widgets:
			bpy.ops.object.mode_set(mode='POSE')
			pose_bones = obj.pose.bones

			root = pose_bones[prefs.root_bone_name]
			apply_widget(context, root, 'ROOT', replace=True)
			root.color.palette = prefs.control_bone_color
			root.custom_shape_wire_width = 1.5

			properties = pose_bones[prefs.property_bone_name]
			apply_widget(context, properties, 'GEAR', replace=True)
			properties.custom_shape_wire_width = 1.5
			properties.lock_location = (True, True, True)
			properties.lock_rotation = (True, True, True)
			properties.lock_scale = (True, True, True)

			bpy.ops.object.mode_set(mode='OBJECT')

		self.report({'INFO'}, "Created RigTools Human skeleton")
		return {'FINISHED'}


def _menu_func(self, context):
	self.layout.operator(
		RIG_OT_create_human_skeleton.bl_idname,
		text="RigTools Human Skeleton",
		icon='ARMATURE_DATA',
	)


classes = (
	RIG_OT_create_human_skeleton,
)


def register():
	for cls in classes:
		bpy.utils.register_class(cls)
	bpy.types.VIEW3D_MT_armature_add.append(_menu_func)


def unregister():
	bpy.types.VIEW3D_MT_armature_add.remove(_menu_func)
	for cls in reversed(classes):
		bpy.utils.unregister_class(cls)
