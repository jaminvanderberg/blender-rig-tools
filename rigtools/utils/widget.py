# Widgets that should keep their proportions when scaled (everything else scales X/Z only, keeping bone length)
UNIFORM_SCALE_WIDGETS = {'SPHERE'}

FK_WIDGET_TAPER = 0.2 # tip widget ends at 80% size

def chain_widget_scales(lengths, *, normalize=False, taper=False):
	"""Per-bone widget scale factor for a chain.
	normalize: size every widget to the chain's average bone length.
	taper: shrink widgets toward the tip (only with normalize)."""
	n = len(lengths)
	if not normalize:
		return [1.0] * n
	avg = sum(lengths) / n if n else 0.0
	scales = []
	for i, length in enumerate(lengths):
		s = avg / length
		if taper and n > 1:
			s *= 1.0 - FK_WIDGET_TAPER * i / (n - 1)
		scales.append(s)
	return scales

def widget_scale_xyz(widget_type, s):
	"""custom_shape_scale_xyz for a scale factor."""
	if widget_type in UNIFORM_SCALE_WIDGETS:
		return (s, s, s)
	return (s, 1.0, s)

# Custom property marking a shared standard widget; the value is its widget type
STANDARD_WIDGET_KEY = "rigtools_widget"

def is_standard_widget(obj):
	return obj is not None and STANDARD_WIDGET_KEY in obj

def get_standard_widget(context, widget_type):
	"""The one shared widget for this type, created the first time it's needed"""
	if widget_type == 'NONE':
		return None
	name = f"WGT-{widget_type.title()}"
	wgt = bpy.data.objects.get(name)
	if wgt is None or wgt.get(STANDARD_WIDGET_KEY) != widget_type:
		wgt = next((o for o in bpy.data.objects if o.get(STANDARD_WIDGET_KEY) == widget_type), None)
	if wgt is None:
		wgt = _create_widget(context, widget_type, name)
		wgt[STANDARD_WIDGET_KEY] = widget_type
	return wgt

def _create_widget(context, widget_type, widget_name):
	match widget_type:
		case 'CIRCLE':
			creator = _create_circle_widget
		case 'RECTANGLE':
			creator = _create_rectangle_widget
		case 'FK':
			creator = _create_fk_shape_widget
		case 'BOX':
			creator = _create_box_widget
		case 'PILL':
			creator = _create_pill_widget
		case 'SHOULDER':
			creator = _create_shoulder_widget
		case 'IK':
			creator = _create_ik_widget
		case 'SPHERE':
			creator = _create_sphere_widget
		case 'LINE':
			creator = _create_line_widget
		case 'TWIST':
			creator = _create_twist_widget
		case 'CHEST':
			creator = _create_chest_widget
		case 'ROLL':
			creator = _create_roll_widget
		case 'PADDLE':
			creator = _create_paddle_widget
		case 'ROOT':
			creator = _create_root_widget
		case 'GEAR':
			creator = _create_gear_widget
		case _:
			raise ValueError(f"Invalid widget type: {widget_type}")

	collection = _get_widget_collection(context, get_preferences(context).widget_collection)
	wgt = creator(widget_name)
	collection.objects.link(wgt)
	return wgt

def apply_widget(context, pose_bone, widget_type):
	wgt = get_standard_widget(context, widget_type)
	pose_bone.custom_shape = wgt
	return wgt

def _get_widget_collection(context, collection_name):
	coll = bpy.data.collections.get(collection_name)
	if not coll:
		coll = bpy.data.collections.new(collection_name)
		context.scene.collection.children.link(coll)
		coll.hide_viewport = True
		coll.hide_render = True
	return coll

def _create_sphere_widget(widget_name):    
	verts = []
	edges = []
	segments = 12
	
	for axis in ['XY', 'XZ', 'YZ']:
		start_idx = len(verts)
		for i in range(segments):
			angle = (2 * math.pi * i) / segments
			cos_a = math.cos(angle) * 0.5
			sin_a = math.sin(angle) * 0.5
			
			match axis:
				case 'XY':
					verts.append((cos_a, sin_a, 0.0))
				case 'XZ':
					verts.append((cos_a, 0.0, sin_a))
				case 'YZ':
					verts.append((0.0, cos_a, sin_a))
					
			next_i = (i + 1) % segments
			edges.append((start_idx + i, start_idx + next_i))
			
	mesh = bpy.data.meshes.new(widget_name)
	mesh.from_pydata(verts, edges, [])
	mesh.update()
	
	wgt = bpy.data.objects.new(widget_name, mesh)
	
	return wgt

